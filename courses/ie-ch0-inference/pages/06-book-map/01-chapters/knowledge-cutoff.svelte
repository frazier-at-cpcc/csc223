<h1>The Knowledge Cutoff</h1>

<p>
  Like LLMs, books have knowledge cutoffs. The authors finished <cite>Inference Engineering</cite> in January 2026.
</p>

<h2>What changes and what lasts</h2>

<p>
  Details will change. New GPUs will ship, inference engines will add features, and new models will appear. Specific
  product names and version numbers in this course reflect the state of the field at the cutoff.
</p>

<p>
  The principles, concepts, and foundational technologies last longer. The three layers, the six model performance
  techniques, and the levels of infrastructure scale give a background that remains useful for years.
</p>
