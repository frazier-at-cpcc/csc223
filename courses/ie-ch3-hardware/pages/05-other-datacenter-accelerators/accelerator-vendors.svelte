<h1>Accelerator Vendors Beyond NVIDIA</h1>

<p>
  NVIDIA's lead in AI hardware has made it the world's most valuable company. It is far from the only company that
  builds hardware for AI inference. Industry giants such as Amazon and Google, and a large crop of startups, are
  investing billions of dollars in alternatives to NVIDIA GPUs.
</p>
<p>
  This course focuses on NVIDIA GPUs. The following vendors offer the other notable options for running model
  inference.
</p>

